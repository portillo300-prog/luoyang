#!/usr/bin/env python3
"""Story clips for the app: converts the verified clips (m4a, from Alfonso Tools/wandan-audio/clips) to small mono AAC in audio/
and writes audio-own.js. Usage: python3 scripts/own-audio.py [clips folder]   (default ../../../wandan-audio/clips)
Which IDs exist and the text each says come from wandan-audio/rows.json (the same IDs as the recording sheet). Originals are only read."""
import json, os, re, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, '..', '..', '..', 'wandan-audio', 'clips')
rows = json.load(open(os.path.join(src, '..', 'rows.json'), encoding='utf-8'))
norm = lambda t: re.sub(r'[\s，。！？、：；,.!?:;“”‘’"\'「」()（）…]', '', t)
os.makedirs(os.path.join(root, 'audio'), exist_ok=True)
by_id, by_text = {}, {}
for r in rows:
    i = r['id']; a = os.path.join(src, i + '.m4a'); out = os.path.join(root, 'audio', i + '.m4a')
    if not os.path.exists(a): continue
    tmp = tempfile.mkdtemp(); w = os.path.join(tmp, 'a.wav'); m = os.path.join(tmp, 'b.m4a')
    subprocess.run(['afconvert', '-f', 'WAVE', '-d', 'LEI16@22050', '-c', '1', a, w], check=True)
    subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '48000', '-c', '1', w, m], check=True)
    os.replace(m, out)
    info = subprocess.run(['afinfo', out], capture_output=True, text=True).stdout
    secs = float(re.search(r'estimated duration: ([0-9.]+)', info).group(1))
    by_id[i] = {'f': 'audio/' + i + '.m4a', 'secs': round(secs, 2)}
    by_text.setdefault(norm(r['zh']), i)
open(os.path.join(root, 'audio-own.js'), 'w', encoding='utf-8').write(
    '/* GENERATED by scripts/own-audio.py (narrator clips, one per recording-sheet ID). Do not edit by hand. */\n'
    'window.AUDIO_OWN = ' + json.dumps({'byId': by_id, 'byText': by_text}, ensure_ascii=False, separators=(',', ':')) + ';\n')
tot = sum(os.path.getsize(os.path.join(root, v['f'])) for v in by_id.values())
print(len(by_id), 'clips,', round(tot / 1e6, 1), 'MB in audio/; audio-own.js written')
